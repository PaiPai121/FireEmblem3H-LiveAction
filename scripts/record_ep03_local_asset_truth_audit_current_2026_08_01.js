function readJson(file) {
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

function writeJson(file, data) {
  fs.writeFileSync(file, `${JSON.stringify(data, null, 2)}\n`);
}

function upsertBy(items, key, item) {
  const index = items.findIndex((candidate) => candidate[key] === item[key]);
  if (index === -1) items.push(item);
  else items[index] = item;
}

function shotPath(order, shotId, frameSetKey, role) {
  const dir = `${epRoot}/delivery/identity_locked_keyframe_regeneration_2026-08-01/shots/${String(order).padStart(3, "0")}_${shotId}`;
  const suffix = frameSetKey === "local_source_locked_regen_v3"
    ? "local_source_locked_regen_v3_2026-08-01"
    : "local_asset_locked_regen_v1_2026-08-01";
  const name = frameSetKey === "local_source_locked_regen_v3"
    ? `${role}_frame_local_source_locked_regen_v3_2026-08-01.png`
    : `${role}_frame_local_asset_locked_regen_v1_2026-08-01.png`;
  return `${dir}/${suffix}/${name}`;
}

function storyboardPath(shotId, frameSetKey, role) {
  const suffix = frameSetKey === "local_source_locked_regen_v3"
    ? "local_source_locked_regen_v3_2026-08-01"
    : "local_asset_locked_regen_v1_2026-08-01";
  const name = frameSetKey === "local_source_locked_regen_v3"
    ? `${role}_frame_local_source_locked_regen_v3_2026-08-01.png`
    : `${role}_frame_local_asset_locked_regen_v1_2026-08-01.png`;
  return `storyboards/${shotId}/${suffix}/${name}`;
}

function reviewMarkdown(shotId) {
  return `production_system/reviews/${shotId.toLowerCase()}_local_asset_truth_audit_2026-08-01.md`;
}

function reviewText(shotId, audit) {
  return `# ${shotId} Local Asset Truth Audit / 2026-08-01

Reviewer role: pipeline-gate-qa-agent
Decision: ${audit.decision}

## Finding

${audit.finding}

## Required Revision

${audit.requiredRevision}

## Gate Correction

This supersedes the earlier still-frame pass language for this frame set. The generated images may remain on disk as traceable review evidence, but they must not be presented as approved local-asset-locked keyframes or as ready-for-video assets.
`;
}

function main() {
  const delivery = readJson(paths.deliveryManifest);
  const queue = readJson(paths.queue);
  const artifacts = readJson(paths.artifactManifest);
  const reviews = readJson(paths.reviewManifest);
  const identityReview = readJson(paths.identityReview);
  identityReview.shots = identityReview.shots || {};
  identityReview.identity_regeneration_frame_sets = identityReview.identity_regeneration_frame_sets || {};

  const summaryLines = [
    "# EP03 Local Asset Truth Audit / 2026-08-01",
    "",
    "User-facing correction: the current generated keyframes often reference local material, but referencing is not the same as preserving local selected.png identity. This audit demotes misleading pass statuses and preserves the images only as review evidence or layout candidates.",
    "",
    "## Shot Decisions",
    "",
  ];

  for (const [shotId, audit] of Object.entries(audits)) {
    const deliveryShot = (delivery.shots || []).find((shot) => shot.id === shotId);
    const queueShot = (queue.shots || []).find((shot) => shot.id === shotId);
    if (!deliveryShot || !queueShot) throw new Error(`${shotId} missing from manifests`);
    const order = deliveryShot.order;
    const frames = {
      start: shotPath(order, shotId, audit.frameSetKey, "start"),
      key: shotPath(order, shotId, audit.frameSetKey, "key"),
      end: shotPath(order, shotId, audit.frameSetKey, "end"),
    };
    const storyboardFrames = {
      start: storyboardPath(shotId, audit.frameSetKey, "start"),
      key: storyboardPath(shotId, audit.frameSetKey, "key"),
      end: storyboardPath(shotId, audit.frameSetKey, "end"),
    };
    const mdPath = reviewMarkdown(shotId);
    fs.writeFileSync(`${epRoot}/${mdPath}`, reviewText(shotId, audit));

    deliveryShot.status = audit.deliveryStatus;
    deliveryShot.visual_audit_decision = audit.decision;
    deliveryShot.visual_audit_finding = audit.finding;
    deliveryShot.required_revision = audit.requiredRevision;
    deliveryShot.regenerated_frames = frames;
    deliveryShot.video_prompt_qa_decision = "blocked_until_local_asset_truth_audit_passes";
    deliveryShot.motion_probe_status = "blocked_until_local_asset_truth_audit_passes";
    deliveryShot.approved_for_video_blockers = [
      "current generated faces are not proven against local selected.png identity plates",
      "video-prompt QA has not been rerun against corrected real frames",
      "short motion probe and strict adjacent continuity are pending after corrected frames",
    ];

    queueShot.status = audit.queueStatus;
    queueShot.visual_audit_decision = audit.decision;
    queueShot.visual_audit_finding = audit.finding;
    queueShot.required_revision = audit.requiredRevision;
    queueShot[audit.frameSetKey] = {
      ...(queueShot[audit.frameSetKey] || {}),
      frame_set_id: audit.frameSetId,
      frames: storyboardFrames,
      review_markdown: mdPath,
      decision: audit.decision,
      reason: audit.finding,
    };

    const frameSet = identityReview.identity_regeneration_frame_sets[audit.frameSetId] || {};
    identityReview.identity_regeneration_frame_sets[audit.frameSetId] = {
      ...frameSet,
      frames,
      storyboard_frames: storyboardFrames,
      review_markdown: mdPath,
      decision: audit.decision,
      reason: audit.finding,
      required_revision: audit.requiredRevision,
    };
    identityReview.shots[shotId] = {
      ...(identityReview.shots[shotId] || {}),
      decision: audit.decision,
      reason: audit.finding,
      latest_regeneration_frame_set: audit.frameSetId,
      supersedes_previous_pass: true,
    };

    const artifact = artifacts.artifacts.find((item) => item.id === audit.artifactId);
    if (artifact) {
      artifact.status = audit.decision;
      artifact.risk_flags = Array.from(new Set([...(artifact.risk_flags || []), "local_asset_truth_audit_demoted", "not_approved_for_video"]));
      artifact.notes = audit.finding;
    }

    upsertBy(reviews.reviews, "review_id", {
      artifact_id: audit.artifactId,
      review_id: `review-2026-08-01-${shotId}-local-asset-truth-audit-current`,
      reviewer_role: "pipeline-gate-qa-agent",
      reviewer: "codex",
      created_at: createdAt,
      decision: audit.decision,
      blocking_issues: audit.decision === "blocked_needs_revision" ? [audit.finding] : [],
      required_revisions: [audit.requiredRevision],
      rubric: audit.rubric,
      reviewed_paths: [
        frames.start,
        frames.key,
        frames.end,
        storyboardFrames.start,
        storyboardFrames.key,
        storyboardFrames.end,
        mdPath,
      ],
    });

    summaryLines.push(`- ${shotId}: ${audit.decision} - ${audit.finding}`);
  }

  fs.writeFileSync(`${epRoot}/production_system/reviews/ep03_local_asset_truth_audit_2026-08-01.md`, `${summaryLines.join("\n")}\n`);
  writeJson(paths.deliveryManifest, delivery);
  writeJson(paths.queue, queue);
  writeJson(paths.artifactManifest, artifacts);
  writeJson(paths.reviewManifest, reviews);
  writeJson(paths.identityReview, identityReview);

  console.log("recorded current EP03 local asset truth audit and demoted misleading pass statuses");
}

main();
